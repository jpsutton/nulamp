//! Generates nulamp's original built-in skin.
//!
//! Every bitmap follows the sizes and layouts in spec 01 §2.2 and 02–05, so that skin
//! authors' expectations hold. The artwork is drawn procedurally and is original.

mod canvas;
mod eqwin;
pub mod font;
mod framewin;
mod mainwin;

use nulamp_skin::{Bitmap, bmp};

/// All built-in skin bitmaps, by file name.
pub fn bitmaps() -> Vec<(&'static str, Bitmap)> {
    vec![
        ("main.bmp", mainwin::main_bmp().0),
        ("titlebar.bmp", mainwin::titlebar().0),
        ("cbuttons.bmp", mainwin::cbuttons().0),
        ("playpaus.bmp", mainwin::playpaus().0),
        ("monoster.bmp", mainwin::monoster().0),
        ("shufrep.bmp", mainwin::shufrep().0),
        ("numbers.bmp", mainwin::numbers().0),
        ("volume.bmp", mainwin::volume().0),
        ("balance.bmp", mainwin::balance().0),
        ("posbar.bmp", mainwin::posbar().0),
        ("text.bmp", mainwin::text_bmp().0),
        ("eqmain.bmp", eqwin::eqmain(false).0),
        ("eqmain_iso.bmp", eqwin::eqmain(true).0),
        ("eq_ex.bmp", eqwin::eq_ex().0),
        ("pledit.bmp", framewin::pledit().0),
        ("gen.bmp", framewin::gen_bmp().0),
        ("genex.bmp", framewin::genex().0),
        ("video.bmp", framewin::video_like("VIDEO").0),
        ("mb.bmp", framewin::video_like("BROWSER").0),
    ]
}

/// Encodes a bitmap as compactly as the BMP format allows (RLE8 when it fits).
pub fn encode(b: &Bitmap) -> Vec<u8> {
    let full = bmp::encode_24(b);
    match bmp::encode_8(b, true) {
        Some(rle) if rle.len() < full.len() => rle,
        _ => full,
    }
}

/// All built-in skin files (bitmaps, `pledit.txt`, `readme.txt`), by file name.
pub fn files() -> Vec<(String, Vec<u8>)> {
    let mut out: Vec<(String, Vec<u8>)> = bitmaps()
        .into_iter()
        .map(|(n, b)| (n.to_string(), encode(&b)))
        .collect();
    out.push((
        "pledit.txt".into(),
        b"[Text]\r\nNormal=#3CF06E\r\nCurrent=#FFFFFF\r\nNormalBG=#0A0D10\r\nSelectedBG=#1E4E80\r\nmbFG=#3CF06E\r\nmbBG=#0A0D10\r\n".to_vec(),
    ));
    out.push((
        "readme.txt".into(),
        b"nulamp built-in skin.\r\nOriginal artwork generated by tools/skingen.\r\n".to_vec(),
    ));
    out
}
