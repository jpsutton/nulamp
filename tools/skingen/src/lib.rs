//! Generates nulamp's original built-in skin.
//!
//! Every bitmap follows the sizes and layouts in spec 01 §2.2 and 02–05, so that skin
//! authors' expectations hold. The artwork is drawn procedurally and is original.

mod canvas;
mod eqwin;
pub mod font;
mod framewin;
mod mainwin;

use nulamp_skin::{Bitmap, bmp};

